"""Shared mesh, glTF buffer and math helpers for asset generators and CPU previews.

Standard library only. Geometry uses metres/cells and +Y up; matrices are row-major
in Python and glTF matrix arrays are column-major. Keep generated bytes stable:
python3 -B tools/test_asset_regeneration.py.
"""
import copy
import json
import math
from pathlib import Path
import struct


def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


IDENTITY = [[int(i == j) for j in range(4)] for i in range(4)]


def multiply(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(4)) for j in range(4)] for i in range(4)]


def point(m, p, w=1):
    return tuple(sum(m[i][j] * p[j] for j in range(3)) + m[i][3] * w for i in range(3))


def unit(v):
    n = math.sqrt(sum(x * x for x in v))
    return tuple(x / n for x in v) if n > 1e-12 else (0, 1, 0)


def matrix(n):
    if "matrix" in n:
        return [[n["matrix"][j * 4 + i] for j in range(4)] for i in range(4)]
    x, y, z, w = n.get("rotation", (0, 0, 0, 1))
    t, s = n.get("translation", (0, 0, 0)), n.get("scale", (1, 1, 1))
    m = [[1-2*y*y-2*z*z, 2*x*y-2*z*w, 2*x*z+2*y*w, t[0]],
         [2*x*y+2*z*w, 1-2*x*x-2*z*z, 2*y*z-2*x*w, t[1]],
         [2*x*z-2*y*w, 2*y*z+2*x*w, 1-2*x*x-2*y*y, t[2]], [0, 0, 0, 1]]
    for i in range(3):
        for j in range(3):
            m[i][j] *= s[j]
    return m


def linear(v):
    return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4


class GltfBuffer:
    """Append aligned views/accessors to one buffer in a glTF document."""

    def __init__(self, data, buffer=0):
        self.data = data
        self.buffer = buffer
        self.blob = bytearray()

    def view(self, raw, target=34962):
        while len(self.blob) % 4:
            self.blob.append(0)
        views = self.data["bufferViews"]
        views.append({"buffer": self.buffer, "byteOffset": len(self.blob), "byteLength": len(raw),
                      **({"target": target} if target else {})})
        self.blob.extend(raw)
        return len(views) - 1

    def accessor(self, rows, kind, ctype=5126, target=34962, *, bounds=None):
        # Static meshes use flat scalar indices; skinned meshes use one-column rows.
        nested = kind != "SCALAR" or (rows and isinstance(rows[0], (tuple, list)))
        flat = [v for row in rows for v in row] if nested else rows
        raw = struct.pack("<" + len(flat) * {5121: "B", 5123: "H", 5125: "I", 5126: "f"}[ctype], *flat)
        a = {"bufferView": self.view(raw, target), "componentType": ctype, "count": len(rows), "type": kind}
        include_bounds = kind == "VEC3" if bounds is None else bounds
        if include_bounds:
            a.update(min=[min(r[i] for r in rows) for i in range(3)], max=[max(r[i] for r in rows) for i in range(3)])
        self.data["accessors"].append(a)
        return len(self.data["accessors"]) - 1


def write_gltf(path, data, blob, *, buffer=0, compact=False):
    """Write a JSON/bin pair, retaining each generator's established JSON layout."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    info = {"uri": path.with_suffix(".bin").name, "byteLength": len(blob)}
    buffers = data.setdefault("buffers", [])
    if buffer == len(buffers):
        buffers.append(info)
    else:
        buffers[buffer] = info
    path.with_suffix(".bin").write_bytes(blob)
    encoded = json.dumps(data, separators=(",", ":")) if compact else json.dumps(data, indent=2) + "\n"
    path.write_text(encoded)


class Mesh:
    """Material groups, primitive construction and assembly shared by prop tools."""

    def __init__(self, palette, emissive=None):
        self.palette = palette
        self.emissive = {} if emissive is None else emissive
        self.groups = [[[], [], []] for _ in self.palette]

    def face(self, points, material):
        positions, normals, indices = self.groups[material]
        a, b, c = points[:3]
        u, v = [b[i] - a[i] for i in range(3)], [c[i] - a[i] for i in range(3)]
        n = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]]
        length = math.sqrt(sum(x * x for x in n))
        assert length > 1e-10
        start = len(positions)
        positions.extend(points)
        normals.extend([[x / length for x in n]] * len(points))
        for i in range(1, len(points) - 1):
            indices.extend((start, start + i, start + i + 1))

    def box(self, center, size, material, bevel=0.006, tilt=0, worn=False):
        """Chamfered rectangular extrusion; broad planes, narrow edge highlights."""
        x, y, z = [v / 2 for v in size]
        b = min(bevel, x * 0.4, y * 0.4, z * 0.4)
        rings = []
        for depth, inset in [(-z, 0), (z, 0)]:
            xx, yy = x - inset, y - inset
            ring = [(xx - b, -yy), (xx, -yy + b), (xx, yy - b), (xx - b, yy),
                    (-xx + b, yy), (-xx, yy - b), (-xx, -yy + b), (-xx + b, -yy)]
            if b == 0:
                ring = [(xx, -yy), (xx, yy), (-xx, yy), (-xx, -yy)]
            angle = math.radians(tilt)
            rings.append([(center[0] + px,
                           center[1] + py * math.cos(angle) - depth * math.sin(angle),
                           center[2] + py * math.sin(angle) + depth * math.cos(angle)) for px, py in ring])
        self.face(list(reversed(rings[0])), material)
        self.face(rings[-1], material)
        for j in range(len(rings) - 1):
            for i in range(len(rings[0])):
                k = (i + 1) % len(rings[0])
                edge = 3 if worn and i in (2, 4) else material
                self.face([rings[j][i], rings[j][k], rings[j + 1][k], rings[j + 1][i]], edge)

    def profile(self, points, width, material):
        """Extrude a convex counterclockwise silhouette in the Y/Z plane."""
        area = sum(points[i][0] * points[(i + 1) % len(points)][1]
                   - points[(i + 1) % len(points)][0] * points[i][1] for i in range(len(points)))
        if area < 0:
            points = list(reversed(points))
        rings = [[(x, y, z) for y, z in points] for x in (-width / 2, width / 2)]
        self.face(list(reversed(rings[0])), material)
        self.face(rings[1], material)
        for i in range(len(points)):
            j = (i + 1) % len(points)
            self.face([rings[0][i], rings[0][j], rings[1][j], rings[1][i]], material)

    def tube(self, y, z0, z1, radius, material, bore=0, sides=8):
        rings = [[(math.cos(i * math.tau / sides) * r, y + math.sin(i * math.tau / sides) * r, z)
                  for i in range(sides)] for z, r in [(z0, radius), (z1, radius), (z1, bore), (z0, bore)]]
        for a, b in [(0, 1), (1, 2), (2, 3), (3, 0)] if bore else [(0, 1)]:
            for i in range(sides):
                j = (i + 1) % sides
                self.face([rings[a][i], rings[a][j], rings[b][j], rings[b][i]], material)
        if not bore:
            self.face(list(reversed(rings[0])), material)
            self.face(rings[1], material)

    def section(self, rings, material, sides=8, smooth=False, roundness=2):
        """Closed tapered body; rings are (height, half-width, half-depth, Z)."""
        def curve(v):
            return math.copysign(abs(v) ** (2 / roundness), v)
        rings = [[(rx * curve(math.cos(i * math.tau / sides)), y, z - rz * curve(math.sin(i * math.tau / sides)))
                  for i in range(sides)] for y, rx, rz, z in rings]
        self.face(list(reversed(rings[0])), material)
        start = len(self.groups[material][0])
        for a, b in zip(rings, rings[1:]):
            for i in range(sides):
                j = (i + 1) % sides
                self.face([a[i], a[j], b[j], b[i]], material)
        if smooth:
            positions, normals, _ = self.groups[material]
            sums = {}
            for p, n in zip(positions[start:], normals[start:]):
                total = sums.setdefault(tuple(p), [0.0, 0.0, 0.0])
                for axis in range(3):
                    total[axis] += n[axis]
            for i in range(start, len(positions)):
                n = sums[tuple(positions[i])]
                length = math.sqrt(sum(v * v for v in n))
                normals[i] = tuple(v / length for v in n)
        self.face(rings[-1], material)

    def panel(self, points, material, lift=.012, thickness=.008):
        """Convex +Z-facing plate with a raised, faceted center and closed back."""
        if sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(points, points[1:] + points[:1])) < 0:
            points = list(reversed(points))
        center = tuple(sum(p[i] for p in points) / len(points) + (lift if i == 2 else 0) for i in range(3))
        back = [(x, y, z - thickness) for x, y, z in points]
        back_center = tuple(sum(p[i] for p in back) / len(back) for i in range(3))
        for i, a in enumerate(points):
            j = (i + 1) % len(points)
            self.face([back[j], back[i], back_center], material)
            self.face([a, points[j], center], material)
            self.face([back[i], back[j], points[j], a], material)

    def add(self, other, at=(0, 0, 0), turn=(0, 0, 0)):
        def rotate(v):
            x, y, z = v
            a, b, c = [math.radians(t) for t in turn]
            y, z = y * math.cos(a) - z * math.sin(a), y * math.sin(a) + z * math.cos(a)
            x, z = x * math.cos(b) + z * math.sin(b), -x * math.sin(b) + z * math.cos(b)
            x, y = x * math.cos(c) - y * math.sin(c), x * math.sin(c) + y * math.cos(c)
            return (x, y, z)

        for target, (positions, normals, indices) in zip(self.groups, other.groups):
            offset = len(target[0])
            target[0].extend(tuple(p[i] + at[i] for i in range(3)) for p in map(rotate, positions))
            target[1].extend(map(rotate, normals))
            target[2].extend(i + offset for i in indices)
        return self

    def shell(self, rings, material=0):
        """Open-bottom octagonal helmet shell, with a closed faceted crown."""
        rings = [[(rx * math.cos(i * math.tau / 8), y, -.01 - rz * math.sin(i * math.tau / 8))
                  for i in range(8)] for y, rx, rz in rings]
        for lower, upper in zip(rings, rings[1:]):
            for i in range(8):
                j = (i + 1) % 8
                self.face([lower[i], lower[j], upper[j], upper[i]], material)
        self.face(rings[-1], material)

    def cylinder(self, at, radius, height, material, axis="y", bore=0, sides=8):
        piece = Mesh(self.palette)
        piece.tube(0, -height / 2, height / 2, radius, material, bore=bore, sides=sides)
        self.add(piece, at, {"x": (0, 90, 0), "y": (90, 0, 0), "z": (0, 0, 0)}[axis])

    def rock(self, at, size, material=0, seed=0, flecks=None):
        """A closed irregular six-sided lump, with a stable flat bottom."""
        rings = []
        for level, factor in [(-.5, .68), (-.03, 1), (.30, .64)]:
            rings.append([(at[0] + size[0] / 2 * factor * (1 + .15 * math.sin(i * 7 + seed)) * math.cos(-i * math.tau / 6),
                           at[1] + level * size[1],
                           at[2] + size[2] / 2 * factor * (1 + .12 * math.cos(i * 9 + seed)) * math.sin(-i * math.tau / 6)) for i in range(6)])
        self.face(list(reversed(rings[0])), material)
        for k in range(2):
            for i in range(6):
                j = (i + 1) % 6
                mat = flecks if flecks is not None and (i + seed + k) % 3 == 0 else material
                self.face([rings[k][i], rings[k][j], rings[k + 1][j], rings[k + 1][i]], mat)
        tip = (at[0] + .02 * size[0], at[1] + .5 * size[1], at[2])
        for i in range(6):
            self.face([rings[-1][i], rings[-1][(i + 1) % 6], tip], material)

    def straps(self, width, height, depth, positions=(-.12, .12)):
        for x in positions:
            self.box((x, height, 0), (.024, .012, depth + .008), 2, bevel=.002)
            for z in (-depth / 2, depth / 2):
                self.box((x, height / 2, z), (.024, height, .009), 2, bevel=.002)

    def ball(self, at, radius, material, squash=1.0, sides=10):
        """A smooth closed ovoid; `squash` scales its height."""
        piece = Mesh(self.palette)
        rings = [(radius * squash * math.sin(a), radius * math.cos(a) + 1e-4, radius * math.cos(a) + 1e-4, 0)
                 for a in [math.radians(d) for d in (-80, -45, 0, 45, 80)]]
        piece.section(rings, material, sides=sides, smooth=True)
        self.add(piece, at)

    def cross_mark(self, y, size=.12, z=0):
        self.box((0, y, z), (size * .28, .009, size), 4, bevel=.001)
        for side in (-1, 1):
            self.box((side * size * .32, y, z), (size * .36, .009, size * .28), 4, bevel=.001)

    def write(self, name, out, pieces=None):
        """Write one prop, or shared armour meshes with inventory and bone scenes.

        `pieces`: (name, geometry, inventory translation) tuples. Scene zero
        assembles them; scenes 1..N expose each mesh around its bone origin.
        """
        # Preserve the existing metadata as well as geometry bytes during extraction.
        gltf = {"asset": {"version": "2.0", "generator": "My World make_rifle.py"},
                "scene": 0, "scenes": [], "nodes": [],
                "meshes": [], "materials": [], "accessors": [], "bufferViews": []}
        if pieces:
            gltf["nodes"].append({"name": name, "children": list(range(1, len(pieces) + 1))})
            gltf["scenes"].append({"name": "Stored", "nodes": [0]})
            for i, (label, _, at) in enumerate(pieces):
                gltf["nodes"].append({"name": label, "mesh": i, "translation": at})
            for i, (label, _, _) in enumerate(pieces):
                gltf["scenes"].append({"name": label, "nodes": [len(gltf["nodes"])]})
                gltf["nodes"].append({"name": label, "mesh": i})
        else:
            pieces = [(name, self, (0, 0, 0))]
            gltf["scenes"] = [{"nodes": [0]}]
            gltf["nodes"] = [{"name": name, "mesh": 0}]

        buffer = GltfBuffer(gltf)
        accessor = buffer.accessor

        for i, (material_name, color, metal, rough) in enumerate(self.palette):
            material = {"name": material_name, "pbrMetallicRoughness": {
                "baseColorFactor": [linear(c) for c in color] + [1], "metallicFactor": metal, "roughnessFactor": rough}}
            if i in self.emissive:
                material["emissiveFactor"] = self.emissive[i]
            gltf["materials"].append(material)
        triangles = 0
        for label, geometry, _ in pieces:
            mesh = {"name": label, "primitives": []}
            for i, (positions, normals, indices) in enumerate(geometry.groups):
                if not indices:
                    continue
                mesh["primitives"].append({"material": i, "attributes": {
                    "POSITION": accessor(positions, "VEC3", 5126, 34962),
                    "NORMAL": accessor(normals, "VEC3", 5126, 34962)},
                    "indices": accessor(indices, "SCALAR", 5125, 34963)})
                triangles += len(indices) // 3
            gltf["meshes"].append(mesh)
        write_gltf(Path(out) / (name + ".gltf"), gltf, buffer.blob)
        print(f"{name}: {triangles} triangles, {len(self.palette)} materials, {len(buffer.blob):,} bytes")


class SkinnedAsset(GltfBuffer):
    def __init__(self, source, generator):
        self.source = source
        # Outfit files put their 65 skeleton nodes before the render nodes.
        skeleton_end = max(source.data['skins'][0]['joints']) + 1
        self.data = {"asset": {"version": "2.0", "generator": generator},
                     "scene": 0, "scenes": [{"nodes": []}],
                     "nodes": copy.deepcopy(source.data["nodes"][:skeleton_end]),
                     "meshes": [], "materials": [], "bufferViews": [], "accessors": []}

        super().__init__(self.data)

    def write(self, path):
        path = Path(path)
        g = self.data
        skin = copy.deepcopy(self.source.data["skins"][0])
        skin["inverseBindMatrices"] = self.accessor(self.source.values(skin["inverseBindMatrices"]), "MAT4", target=0)
        g["skins"] = [skin]
        skeleton_nodes = len(g["nodes"])
        roots = sorted(set(range(skeleton_nodes)) - {c for n in g["nodes"] for c in n.get("children", [])})
        g["nodes"].append({"name": "Armature", "children": roots})
        for i, mesh in enumerate(g["meshes"]):
            g["nodes"].append({"name": mesh["name"], "mesh": i, "skin": 0})
        root = len(g["nodes"])
        g["nodes"].append({"name": path.stem, "children": list(range(skeleton_nodes, root))})
        g["scenes"][0]["nodes"] = [root]
        write_gltf(path, g, self.blob)
